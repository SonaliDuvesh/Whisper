def generate_workforce_briefing(
    context: Dict[str, Any],
    provider: Optional[str] = None,
) -> Dict[str, Any]:
    """Generate concise HR operational intelligence briefing using actual data and privacy safeguards."""
    org = context.get("organization", "Organization")
    site = context.get("site", "Workplace Site")
    date = context.get("date", "Current Date")
    risk = context.get("workforce_risk", 0.0)
    sev = context.get("severity", "GREEN")
    sick = context.get("sick_leave", 0.0)
    base_m = context.get("baseline_mean", 0.0)
    cap = context.get("operational_capacity", 100.0)
    z = context.get("z_absence", 0.0)
    tot_emp = context.get("total_employees", 0)
    abs_emp = context.get("absent_employees", 0)
    is_alert = context.get("is_alert", False)

    if sev in ("RED", "ORANGE"):
        situation = (
            f"{org} ({site}) exhibits significant absenteeism deviation on {date}, with sick-leave rates rising to "
            f"{sick:.1f}% ({abs_emp:,} of {tot_emp:,} employees absent). Operational capacity is reduced to {cap:.1f}%, "
            f"elevating the workforce risk score to {risk:.1f}/100 ({sev} severity)."
        )
    elif sev == "YELLOW":
        situation = (
            f"{org} ({site}) shows moderate sick-leave elevation on {date} at {sick:.1f}% "
            f"(baseline: {base_m:.1f}%). Operational capacity remains stable at {cap:.1f}% with risk classified as Yellow."
        )
    else:
        situation = (
            f"{org} ({site}) maintains normal workforce health baseline on {date}. Current sick-leave rate is {sick:.1f}% "
            f"with full operational capacity at {cap:.1f}% (risk score: {risk:.1f}/100, Green severity)."
        )

    evidence = (
        f"Aggregated sick-leave Z-score is currently at +{z:.2f}σ above the historical 28-day baseline "
        f"({base_m:.2f}% ± {context.get('baseline_std', 0.2):.2f}%)."
    )
    if is_alert:
        evidence += " Telemetry satisfies multi-day consecutive qualification criteria, maintaining an active workforce alert."

    if sev in ("RED", "ORANGE"):
        rec = (
            "Recommended HR Actions: Activate departmental staffing contingency rosters, enhance indoor facility ventilation "
            "and sanitation protocols, facilitate voluntary remote or flexible shifts where operationally feasible, and "
            "remind personnel to follow voluntary health policies without punitive attendance measures."
        )
    elif sev == "YELLOW":
        rec = (
            "Recommended HR Actions: Monitor absenteeism trends across subsequent operational shifts, audit hand-sanitizer "
            "and hygiene supplies, and verify shift backup rosters."
        )
    else:
        rec = "Recommended HR Actions: Maintain standard routine organizational wellness and workplace health monitoring."

    if z >= 3.0 or (is_alert and risk >= 75.0):
        conf_level = "High"
        conf_basis = "High confidence based on sustained, statistically significant sick-leave deviation above historical baseline."
    elif z >= 2.0 or risk >= 40.0:
        conf_level = "Moderate"
        conf_basis = "Moderate confidence based on notable single-signal absence deviation."
    else:
        conf_level = "Low"
        conf_basis = "Low confidence reflecting baseline variance."

    return {
        "organization": org,
        "site": site,
        "date": date,
        "situation": situation,
        "supporting_signals": evidence,
        "recommended_action": rec,
        "confidence_level": conf_level,
        "confidence_rationale": conf_basis,
        "privacy_statement": "All workforce indicators are synthetic, aggregated and anonymized. No individual employee health records are collected or processed.",
        "provider_mode": "Local Deterministic Engine (No API Key Required)",
    }

def answer_workforce_question(
    question: str,
    context: Dict[str, Any],
    conversation_history: Optional[List[Dict[str, str]]] = None,
    provider: Optional[str] = None,
) -> Dict[str, str]:
    """Provide privacy-compliant operational answers to questions about workforce trends."""
    clean_q = question.strip()
    q_lower = clean_q.lower()

    individual_keywords = ["who is sick", "employee name", "individual", "fire", "punish", "diagnose", "medical record"]
    if any(kw in q_lower for kw in individual_keywords):
        return {
            "answer": (
                "Workforce intelligence adheres to strict privacy and ethical boundaries: "
                "telemetry is strictly aggregated and anonymized at the organization/site level. "
                "The system does not track, diagnose, or infer records for any individual employee."
            ),
            "mode": "Privacy Safeguard Policy",
        }

    org = context.get("organization", "Selected Organization")
    site = context.get("site", "Workplace Site")
    date = context.get("date", "Current Date")
    risk = context.get("workforce_risk", 0.0)
    sev = context.get("severity", "GREEN")
    sick = context.get("sick_leave", 0.0)
    base_m = context.get("baseline_mean", 0.0)
    cap = context.get("operational_capacity", 100.0)
    z = context.get("z_absence", 0.0)
    is_alert = context.get("is_alert", False)

    if "why" in q_lower and ("risk" in q_lower or "red" in q_lower or "orange" in q_lower or "elevated" in q_lower):
        if sev in ("RED", "ORANGE"):
            return {
                "answer": (
                    f"{org} ({site}) exhibits elevated workforce risk ({risk:.1f}/100, {sev}) because its current "
                    f"sick-leave rate of {sick:.1f}% exceeds its 28-day baseline of {base_m:.1f}% by a Z-score of +{z:.2f}σ, "
                    f"resulting in an available operational capacity of {cap:.1f}%."
                ),
                "mode": "Local Rule-Based Intelligence",
            }
        else:
            return {
                "answer": f"{org} is operating with a low workforce risk score of {risk:.1f}/100 ({sev}) with normal absenteeism of {sick:.1f}%.",
                "mode": "Local Rule-Based Intelligence",
            }

    if "capacity" in q_lower or "available" in q_lower or "operational" in q_lower:
        tot = context.get("total_employees", 0)
        abs_emp = context.get("absent_employees", 0)
        avail = tot - abs_emp
        return {
            "answer": (
                f"Current estimated operational capacity for {org} is {cap:.1f}%. "
                f"Approximately {avail:,} of {tot:,} employees are available for work on {date} ({abs_emp:,} absent)."
            ),
            "mode": "Local Rule-Based Intelligence",
        }

    if "action" in q_lower or "hr" in q_lower or "recommend" in q_lower:
        if sev in ("RED", "ORANGE"):
            return {
                "answer": (
                    "HR should consider: (1) Activating shift backup rosters to mitigate staffing shortfalls, "
                    "(2) Increasing environmental airflow and sanitation at the facility, (3) Offering flexible schedules, "
                    "and (4) Advising symptomatic staff to recuperate at home without penalty."
                ),
                "mode": "Local Rule-Based Intelligence",
            }
        else:
            return {
                "answer": "Current sick-leave indicators are within normal statistical variance. Continue standard passive health monitoring.",
                "mode": "Local Rule-Based Intelligence",
            }

    if "alert" in q_lower or "active" in q_lower:
        if is_alert:
            first_d = context.get("first_alert_date", date)
            return {
                "answer": f"Yes. An active workforce health alert is in effect for {org}, initially triggered on {first_d}.",
                "mode": "Local Rule-Based Intelligence",
            }
        else:
            return {
                "answer": f"No active workforce alert is currently triggered for {org} on {date}.",
                "mode": "Local Rule-Based Intelligence",
            }

    return {
        "answer": (
            f"The workforce telemetry for {org} on {date} shows a sick-leave rate of {sick:.1f}% (baseline {base_m:.1f}%), "
            f"Z-score of +{z:.1f}σ, and operational capacity of {cap:.1f}%. You can ask about absenteeism drivers, capacity, or HR actions."
        ),
        "mode": "Local Rule-Based Intelligence",
    }

